#!/usr/bin/env python3
"""
Compare SCAMP's output .head solutions with the synthetic ground truth
generated by gen_synth.py.

Checks: astrometric RMS vs. true positions < 10 mas for every exposure,
recovered relative zero-points (FLXSCALE) within 0.005 mag.
See gen_synth.py for the full usage.
"""
import sys, os, warnings
import numpy as np
from astropy.io import fits
from astropy.wcs import WCS, FITSFixedWarning

warnings.simplefilter("ignore", FITSFixedWarning)
d = sys.argv[1]
t = np.load(os.path.join(d, "truth.npz"))
D2R = np.pi / 180

def sep_mas(ra1, dec1, ra2, dec2):
    dra = (ra1 - ra2) * np.cos(dec2 * D2R)
    return np.hypot(dra, dec1 - dec2) * 3.6e6

nexp = len(t["zp_off"])
fails = 0
fluxscale = []
print("%-6s %10s %10s %10s %10s" % ("Exp", "before:rms", "before:max", "after:rms", "after:max"))
for e in range(nexp):
    idx, x, y = t["idx%d" % e], t["x%d" % e], t["y%d" % e]
    ra_t, dec_t = t["ra"][idx], t["dec"][idx]
    imhead = fits.open(os.path.join(d, "exp%d.cat" % (e + 1)))[1].data[0][0]
    imhead = imhead if isinstance(imhead, str) else "".join(c.ljust(80) for c in imhead)
    h0 = fits.Header.fromstring(imhead.rstrip("\x00"))
    w0 = WCS(h0)
    hs = fits.Header.fromstring(open(os.path.join(d, "exp%d.head" % (e + 1))).read(), sep="\n")
    h1 = h0.copy()
    for k in ("CD1_1", "CD1_2", "CD2_1", "CD2_2"):
        h1.remove(k, ignore_missing=True)
    h1.update(hs)
    # SCAMP writes TAN+PV (old TPV convention); tell wcslib explicitly
    h1["CTYPE1"], h1["CTYPE2"] = "RA---TPV", "DEC--TPV"
    w1 = WCS(h1)
    # FITS pixel convention: SCAMP/SExtractor use 1-based pixels -> origin=1
    r0 = sep_mas(*w0.all_pix2world(x, y, 1), ra_t, dec_t)
    r1 = sep_mas(*w1.all_pix2world(x, y, 1), ra_t, dec_t)
    print("exp%-3d %8.0f mas %8.0f mas %8.2f mas %8.2f mas" %
          (e + 1, np.sqrt(np.mean(r0**2)), r0.max(), np.sqrt(np.mean(r1**2)), r1.max()))
    fails += np.sqrt(np.mean(r1**2)) > 10.0
    fluxscale.append(hs["FLXSCALE"])

# photometry: FLXSCALE should compensate the injected ZP offsets (relative)
fs = np.array(fluxscale)
dmag_scamp = -2.5 * np.log10(fs / fs.mean())   # mag correction applied by SCAMP
dmag_true = t["zp_off"] - t["zp_off"].mean()
dmag_scamp -= dmag_scamp.mean()
print("\nZero-point offsets (mag):  injected  vs. recovered by SCAMP (FLXSCALE)")
for e in range(nexp):
    print("  exp%d   %+.4f   %+.4f   diff %+.4f" %
          (e + 1, dmag_true[e], -dmag_scamp[e], dmag_true[e] + dmag_scamp[e]))
zperr = np.abs(dmag_true + dmag_scamp).max()
fails += zperr > 0.005
print("\nResult:", "PASSED" if fails == 0 else "%d check(s) FAILED" % fails)
sys.exit(int(fails))
